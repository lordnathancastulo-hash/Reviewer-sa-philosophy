/* Pick questions from every selected topic in proportion to its size, so each topic is covered. */
function build() {
  const ids = Object.keys(TOPIC).filter(i => sel.has(i));
  const total = pool().length;
  const n = count === 'all' ? total : Math.min(+count, total);
  const take = {}; let used = 0;
  ids.forEach(i => { take[i] = Math.min(num(i), Math.max(1, Math.round(n * num(i) / total))); used += take[i]; });
  let guard = 0;
  while (used !== n && guard++ < 1000) {
    const i = ids[guard % ids.length];
    if (used < n && take[i] < num(i)) { take[i]++; used++; }
    else if (used > n && take[i] > 1) { take[i]--; used--; }
  }
  let out = [];
  ids.forEach(i => { out = out.concat(shuffle(BANK.filter(q => q.t === i)).slice(0, take[i])); });
  return shuffle(out);
}

