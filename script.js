function answer(k) {
  const q = S.qs[S.i];
  if (S.locked === S.i) return;
  S.locked = S.i;
  const ok = q.o[k] === q.c;
  S.by[q.t] = S.by[q.t] || { r: 0, t: 0 }; S.by[q.t].t++;
  if (ok) { S.score++; S.by[q.t].r++; } else S.miss.push({ q: q.q, c: q.c, y: q.o[k], e: q.e, t: q.t });
  app.querySelectorAll('.opt').forEach((b, j) => {
    b.disabled = true;
    if (q.o[j] === q.c) { b.classList.add('correct'); b.querySelector('.k').textContent = '\u2713'; }
    else if (j === k) { b.classList.add('wrong'); b.querySelector('.k').textContent = '\u2717'; }
    else b.classList.add('dim');
  });
  const last = S.i === S.qs.length - 1;
  document.getElementById('fb').innerHTML = `<div class="fb ${ok ? 'ok' : 'no'}"><strong>${ok ? 'Correct!' : 'Not quite.'}</strong>
  ${ok ? '' : `<p>The correct answer is <b>${esc(q.c)}</b>.</p>`}<p>${esc(q.e)}</p></div>
  <button class="primary" type="button" id="nx" style="margin-top:14px">${last ? 'See results' : 'Next question'}</button>`;
  const nx = document.getElementById('nx'); nx.onclick = () => { last ? results() : (S.i++, show()); }; nx.focus();
}

